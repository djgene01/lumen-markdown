param(
    [string]$PublishDir = "artifacts/publish/win-x64",
    [string]$OutFile = "installer/generated/AppFiles.wxs"
)
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

$publish = (Resolve-Path $PublishDir).Path
$files = Get-ChildItem $publish -Recurse -File | Sort-Object FullName

function New-Id([string]$prefix, [string]$key) {
    $sha = [System.Security.Cryptography.SHA1]::Create()
    $hash = $sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($key.ToLowerInvariant()))
    $hex = -join ($hash[0..5] | ForEach-Object { $_.ToString("x2") })
    return "$prefix$hex"
}

# Build the directory tree keyed by relative path ('' is the install root).
$dirs = @{ "" = @{ Id = "INSTALLFOLDER"; Children = New-Object System.Collections.Generic.List[string] } }
foreach ($f in $files) {
    $rel = $f.FullName.Substring($publish.Length).TrimStart('\')
    $parts = $rel -split '\\'
    $current = ""
    for ($i = 0; $i -lt $parts.Length - 1; $i++) {
        $next = if ($current) { "$current\$($parts[$i])" } else { $parts[$i] }
        if (-not $dirs.ContainsKey($next)) {
            $dirs[$next] = @{ Id = (New-Id "dir_" $next); Children = New-Object System.Collections.Generic.List[string] }
            $dirs[$current].Children.Add($next) | Out-Null
        }
        $current = $next
    }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
[void]$sb.AppendLine('<!-- Generated by scripts/gen-installer.ps1. Do not edit by hand. -->')
[void]$sb.AppendLine('<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">')
[void]$sb.AppendLine('  <Fragment>')

foreach ($key in ($dirs.Keys | Sort-Object)) {
    if (-not $key) { continue }
    $parentKey = if ($key.Contains('\')) { $key.Substring(0, $key.LastIndexOf('\')) } else { "" }
    $leaf = if ($key.Contains('\')) { $key.Substring($key.LastIndexOf('\') + 1) } else { $key }
    $parentId = $dirs[$parentKey].Id
    $name = [System.Security.SecurityElement]::Escape($leaf)
    [void]$sb.AppendLine("    <DirectoryRef Id=`"$parentId`">")
    [void]$sb.AppendLine("      <Directory Id=`"$($dirs[$key].Id)`" Name=`"$name`" />")
    [void]$sb.AppendLine('    </DirectoryRef>')
}
[void]$sb.AppendLine('  </Fragment>')
[void]$sb.AppendLine('  <Fragment>')
[void]$sb.AppendLine('    <ComponentGroup Id="AppFiles">')

foreach ($f in $files) {
    $rel = $f.FullName.Substring($publish.Length).TrimStart('\')
    $parts = $rel -split '\\'
    $dirKey = if ($parts.Length -gt 1) { ($parts[0..($parts.Length - 2)] -join '\') } else { "" }
    $dirId = $dirs[$dirKey].Id
    $id = New-Id "cmp_" $rel
    $fileId = New-Id "fil_" $rel
    $source = [System.Security.SecurityElement]::Escape($f.FullName)
    $name = [System.Security.SecurityElement]::Escape($parts[-1])
    [void]$sb.AppendLine("      <Component Id=`"$id`" Directory=`"$dirId`" Guid=`"*`">")
    [void]$sb.AppendLine("        <File Id=`"$fileId`" Source=`"$source`" Name=`"$name`" KeyPath=`"yes`" />")
    [void]$sb.AppendLine('      </Component>')
}

[void]$sb.AppendLine('    </ComponentGroup>')
[void]$sb.AppendLine('  </Fragment>')
[void]$sb.AppendLine('</Wix>')

$target = Join-Path $root $OutFile
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $target) | Out-Null
[IO.File]::WriteAllText($target, $sb.ToString(), (New-Object Text.UTF8Encoding $false))
Write-Host "Generated $OutFile with $($files.Count) files in $($dirs.Count - 1) subdirectories."
